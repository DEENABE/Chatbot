import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const source=fileURLToPath(new URL('../tools/inspection/native/',import.meta.url));
const framework=path.join(process.env.SystemRoot||'C:\\Windows','Microsoft.NET','Framework64','v4.0.30319');
const compiler=path.join(framework,'csc.exe');
const target=path.join(source,'bin');fs.mkdirSync(target,{recursive:true});
const references=['System.dll','System.Core.dll','System.Management.dll','System.Web.Extensions.dll',...['UIAutomationClient.dll','UIAutomationTypes.dll','WindowsBase.dll'].map(f=>path.join(framework,'WPF',f))];
execFileSync(compiler,['/nologo','/target:exe','/platform:x64','/optimize+','/out:'+path.join(target,'WindowsUIAHost.exe'),'/win32manifest:'+path.join(source,'WindowsUIAHost.manifest'),...references.map(f=>'/reference:'+f),path.join(source,'WindowsUIAHost.cs')],{stdio:'inherit',windowsHide:true});
console.log(JSON.stringify({success:true,helper:path.join(target,'WindowsUIAHost.exe'),platform:'x64',runtime:'.NET Framework 4',dpi:'PerMonitorV2'}));
